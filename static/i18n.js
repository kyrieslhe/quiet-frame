let lang = localStorage.getItem('quiet-frame-language') === 'en' ? 'en' : 'zh';

function t(key, values = {}) {
    return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), translations[lang][key] || key);
}

function localize(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(el => el.textContent = t(el.dataset.i18n));
    root.querySelectorAll('[data-placeholder]').forEach(el => el.placeholder = t(el.dataset.placeholder));
    root.querySelectorAll('[data-aria]').forEach(el => el.setAttribute('aria-label', t(el.dataset.aria)));
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.title = lang === 'zh' ? '留影 — Quiet Frame' : 'Quiet Frame — Photography';
    for (const code of ['zh', 'en']) document.querySelector(`#lang-${code}`).setAttribute('aria-pressed', String(code === lang));
}
